#!/usr/bin/env python3
"""Build recovery trajectories from failed TRAIN rollouts.

This script turns a failed sampled rollout plus its verified gold trajectory into a normal
model-visible trajectory:

  failed exploratory prefix (without the wrong final answer)
  -> first-person recovery reasoning
  -> verified gold tool chain

No new tool is introduced. The recovery state lives only in the next step's `<think>` text, and all
tool outputs are regenerated by the harness. The output is intentionally compatible with
build_sft_data.py.
"""
from __future__ import annotations

