TOOL_CALL_RE = re.compile(r"<tool_call>\s*\{.*", re.S)
SOURCE_REF_KEYS = ("table", "left", "right")
TRAIN_ID_RE = re.compile(r"^spider_train_(\d+)$")
BAD_PATH_MARKERS = ("/dev", "_dev", "dev1034", "spider_dev")


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open(encoding="utf-8") as source:
        return [json.loads(line) for line in source if line.strip()]


def write_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as sink:
        for record in records:
            sink.write(json.dumps(record, ensure_ascii=False, default=str) + "\n")


def looks_like_dev(path: Path) -> bool:
    text = str(path).replace("\\", "/").lower()
    return any(marker in text for marker in BAD_PATH_MARKERS)


def trajectory_index(path: Path) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for traj in load_jsonl(path):
        traj = normalize_legacy_memory(traj)
        out[traj["trajectory_id"]] = traj
    return out


def candidate_trajectory_id(candidate: dict[str, Any]) -> str:
    if candidate.get("trajectory_id"):
        return str(candidate["trajectory_id"])
    example_index = candidate.get("example_index")
    if example_index is None:
        raise ValueError("candidate has neither trajectory_id nor example_index")
    return f"spider_train_{int(example_index)}"


def extract_think_from_model_output(text: str, fallback: str) -> str:
    prefix = TOOL_CALL_RE.sub("", text or "").strip()
    prefix = re.sub(r"</?think>", "", prefix).strip()
    prefix = re.sub(r"\s+", " ", prefix)
    return prefix or fallback


def exploratory_think(tool: str, args: dict[str, Any], question: str) -> str:
    """Safe target text for failed-prefix actions.

    We do not clone the failed model's original think verbatim because it often contains exactly the
    hallucination we want the next model to recover from (e.g. claiming unseen schemas lack a
    column). The failed tool call itself remains visible, but the supervised text frames it as a
    tentative probe, not as a justified conclusion.
    """
    if tool == "describe_table":
        tables = args.get("tables") or []
        return (
            f"I tentatively inspect the schema of `{compact_args(tables)}` because the question is "
            f"`{question}` and this table might contain the needed concept. This is an exploratory "
            "path that I will revise if the observation does not support the question."
        )
    if tool == "inspect_column":
        return (
            f"I tentatively inspect `{args.get('table')}.{args.get('column')}` to test whether this "
            "column matches the question concept. I should treat the result as evidence for or "
            "against this path, not as proof that other tables are irrelevant."
        )
    if tool in {"aggregate", "condition_filter", "project", "group_aggregate",
                "join_tables", "extreme_value_select", "set_op"}:
        return (
            f"I continue this tentative path with `{tool}` using `{compact_args(args)}`. If the "
            "result does not answer the question, I should backtrack to the schema evidence instead "
            "of forcing this path."
        )
    return (
        f"I try `{tool}` with `{compact_args(args)}` as an exploratory step and will revise the path "
        "if the observation does not support the question."
    )


def compact_args(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), default=str)


def is_source_table(name: Any, source_tables: set[str]) -> bool:
    return isinstance(name, str) and name in source_tables


def walk_conditions(cond: Any):
    if not isinstance(cond, dict):
        return
    yield cond
    for key in ("and", "or", "conditions"):
        for child in cond.get(key, []) or []:
            yield from walk_conditions(child)
    if "not" in cond:
        yield from walk_conditions(cond["not"])


def string_filter_columns(cond: Any) -> set[str]:
    out = set()
    for item in walk_conditions(cond):
        if isinstance(item.get("value"), str) and isinstance(item.get("column"), str):
            if item.get("op") in {"=", "==", "!=", "contains", "like", "in"}:
                out.add(item["column"].split("__", 1)[-1])
    return out


def remap_conditions(cond: Any, step_map: dict[str, str], table_map: dict[str, str]) -> None:
    if not isinstance(cond, dict):
        return
    for key in ("and", "or", "conditions"):
        for child in cond.get(key, []) or []:
            remap_conditions(child, step_map, table_map)
    if "not" in cond:
        remap_conditions(cond["not"], step_map, table_map)
    if isinstance(cond.get("value_ref"), str):
        cond["value_ref"] = step_map.get(cond["value_ref"], cond["value_ref"])
    if isinstance(cond.get("in_table"), str):
        cond["in_table"] = table_map.get(cond["in_table"], cond["in_table"])


def remap_args(tool: str, args: dict[str, Any], step_map: dict[str, str],
               table_map: dict[str, str]) -> dict[str, Any]:
    out = copy.deepcopy(args)
    for key in SOURCE_REF_KEYS:
        if isinstance(out.get(key), str):
            out[key] = table_map.get(out[key], out[key])
    if tool == "condition_filter":
        remap_conditions(out.get("conditions"), step_map, table_map)
    if tool == "answer_from_context":
        out.pop("supporting_memory_ids", None)
        evidence = out.get("evidence")
        if isinstance(evidence, dict) and isinstance(evidence.get("table"), str):
            evidence["table"] = table_map.get(evidence["table"], evidence["table"])
    return out


def safe_execute(h: Harness, ctx: dict[str, Any], tool: str, args: dict[str, Any],
                 step_id: str) -> tuple[str, dict[str, Any], str | None]:
    try:
        out, table_name = execute_tool(h, tool, args, ctx, step_id)
        return "success", out, table_name
    except Exception as exc:  # noqa: BLE001
        err_type = "protocol_error" if isinstance(exc, ProtocolError) else "execution_error"
        return err_type, {"error": {"type": err_type, "message": f"{type(exc).__name__}: {exc}"}}, None


def table_output_name(output: dict[str, Any]) -> str | None:
    table = output.get("table")
    return table if isinstance(table, str) else None


def source_tables_from_overview(initial_overview: dict[str, Any]) -> set[str]:
    return {
        table["table_name"]
        for table in initial_overview.get("tables", [])
        if isinstance(table, dict) and isinstance(table.get("table_name"), str)
    }


def action_table_refs(tool: str, args: dict[str, Any]) -> list[str]:
    refs = []
    for key in SOURCE_REF_KEYS:
        if isinstance(args.get(key), str):
            refs.append(args[key])
    if tool == "answer_from_context":
        evidence = args.get("evidence") or {}
        if isinstance(evidence, dict) and isinstance(evidence.get("table"), str):
            refs.append(evidence["table"])
    return refs


def describe_step_text(tables: list[str], question: str, recovery: bool) -> str:
    table_list = ", ".join(f"`{table}`" for table in tables)
    if recovery:
        return (
            f"The observations so far do not fully establish the requested evidence, so I go back to "
            f"schema inspection. I describe {table_list} to check whether these tables expose concepts "
            "that better match the question before choosing the next operation."
        )
    return (
        f"I describe {table_list} because I need the source schema before using these tables to "
        f"answer: {question}"
    )


def inspect_step_text(table: str, column: str) -> str:
    return (
        f"I inspect `{table}.{column}` because the next operation may rely on this text column, and I "
        "need its observed value domain before using a literal."
    )


def action_text(tool: str, args: dict[str, Any], question: str, *, recovery_prefix: str = "") -> str:
    base = ""
    if tool == "condition_filter":
        base = (
            f"I now filter `{args.get('table')}` with conditions "
            f"`{compact_args(args.get('conditions'))}` because this keeps the rows needed for the "
            "question."
        )
    elif tool == "project":
        base = (
            f"I now project `{compact_args(args.get('expressions', []))}` from `{args.get('table')}` "
            "so the result contains exactly the requested fields."
        )
    elif tool == "aggregate":
        base = (
            f"I now compute `{args.get('op')}` over `{args.get('column')}` from `{args.get('table')}` "
            "because the question asks for this scalar result."
        )
    elif tool == "group_aggregate":
        base = (
            f"I now group `{args.get('table')}` by `{compact_args(args.get('group_by', []))}` and "
            f"compute `{compact_args(args.get('aggregations', []))}` because the question requires "
            "grouped evidence."
        )
    elif tool == "join_tables":
        base = (
            f"I now join `{args.get('left')}` with `{args.get('right')}` on "
            f"`{compact_args(args.get('on', []))}` so the columns required by the question are in "
            "one table."
        )
    elif tool == "extreme_value_select":
        base = (
            f"I now order/select rows from `{args.get('table')}` using "
            f"`{compact_args(args.get('order_by', []))}` because the question asks for an extreme "
            "or ordered result."
        )
    elif tool == "set_op":
        base = (
            f"I now apply `{args.get('op')}` between `{args.get('left')}` and `{args.get('right')}` "
            "because the answer depends on combining these two result sets."
        )
    elif tool == "answer_from_context":
        evidence = (args.get("evidence") or {}).get("table")
        if evidence:
            base = f"The evidence table `{evidence}` contains the requested rows, so I answer from it."
        else:
            base = "The previous scalar result directly answers the question, so I answer from it."
    else:
        base = f"I now call `{tool}` with `{compact_args(args)}` because it advances the answer."
    return (recovery_prefix + " " + base).strip()


def first_recovery_prefix(candidate: dict[str, Any], failed_prefix_len: int) -> str:
    bucket = candidate.get("bucket", "failure")
    return (
        f"The earlier {failed_prefix_len} exploratory step(s) produced evidence with a `{bucket}` "
        "symptom, so my current assumption is not supported well enough. I should keep any useful "
        "observations but choose the next operation from the schema evidence instead of forcing the "
        "same path."
    )


def append_tool_step(
    steps: list[dict[str, Any]],
    h: Harness,
    ctx: dict[str, Any],
    created: set[str],
    *,
    tool: str,
    args: dict[str, Any],
    think: str,
    allow_error: bool = False,
) -> tuple[str, dict[str, Any], str | None]:
    step_id = f"step_{len(steps) + 1}"
    if tool == "answer_from_context":
        steps.append({
            "step_id": step_id,
            "think": think,
            "tool_call": {"tool": tool, "arguments": args},
            "tool_output": {"final_answer": args.get("answer")},
        })
        return "success", {"final_answer": args.get("answer")}, None

    status, output, table_name = safe_execute(h, ctx, tool, args, step_id)
    if status != "success" and not allow_error:
        raise RuntimeError(f"{step_id} {tool} failed: {output}")
    if table_name:
        created.add(table_name)
    item = {
        "step_id": step_id,
        "think": think,
        "tool_call": {"tool": tool, "arguments": args},
        "tool_status": status,
        "tool_output": output,
    }
    if status != "success":
        item["recovery_error_observation"] = True
    steps.append(item)
    return status, output, table_name


def build_one(candidate: dict[str, Any], clean: dict[str, Any], *,
              max_failed_prefix_steps: int) -> tuple[dict[str, Any] | None, str]:
    clean = normalize_legacy_memory(clean)
    h = Harness(db_path(clean["source"]["db_id"]))
    ctx = new_ctx()
    created: set[str] = set()
    steps: list[dict[str, Any]] = []
    source_tables = source_tables_from_overview(clean["initial_state"]["dataset_overview"])
    described: set[str] = set()
    inspected: set[tuple[str, str]] = set()
    failed_seen: set[str] = set()
    failed_kept = 0

    for turn in (candidate.get("failed_sample") or {}).get("turns") or []:
        parsed = turn.get("parsed") or {}
        tool = parsed.get("tool")
        args = parsed.get("arguments")
        if not tool or not isinstance(args, dict):
            continue
        if tool == "answer_from_context":
            break
        dedupe_key = f"{tool}:{compact_args(args)}"
        if dedupe_key in failed_seen:
            continue
        failed_seen.add(dedupe_key)
        think = exploratory_think(tool, args, clean["question"])
        status, output, table_name = append_tool_step(
            steps, h, ctx, created, tool=tool, args=copy.deepcopy(args), think=think, allow_error=True
        )
        if turn.get("model_output"):
            steps[-1].setdefault("source_rollout", {})["model_output"] = turn["model_output"]
        if tool == "describe_table" and status == "success":
            for table in args.get("tables") or []:
                if isinstance(table, str):
                    described.add(table)
        if tool == "inspect_column" and status == "success":
            inspected.add((str(args.get("table")), str(args.get("column"))))
        failed_kept += 1
        if failed_kept >= max_failed_prefix_steps:
            break

    table_map: dict[str, str] = {}
    step_map: dict[str, str] = {}
    recovery_prefix = first_recovery_prefix(candidate, failed_kept)
    used_recovery_prefix = False

    def ensure_described(tables: list[str]) -> None:
        missing = [table for table in tables if table in source_tables and table not in described]
        if not missing:
            return
        append_tool_step(
            steps, h, ctx, created,
            tool="describe_table",
            args={"tables": missing},
            think=describe_step_text(missing, clean["question"], recovery=failed_kept > 0),
        )
        described.update(missing)

    def ensure_inspected(table: str, columns: set[str]) -> None:
        for column in sorted(columns):
            key = (table, column)
            if key in inspected:
                continue
            append_tool_step(
                steps, h, ctx, created,
                tool="inspect_column",
                args={"table": table, "column": column},
                think=inspect_step_text(table, column),
            )
            inspected.add(key)

    for clean_step in clean["steps"]:
        call = clean_step["tool_call"]
        tool = call["tool"]
        args = remap_args(tool, call["arguments"], step_map, table_map)
        source_refs = [ref for ref in action_table_refs(tool, args) if is_source_table(ref, source_tables)]
        ensure_described(source_refs)
        if tool == "condition_filter" and is_source_table(args.get("table"), source_tables):
            ensure_inspected(args["table"], string_filter_columns(args.get("conditions")))
        if tool == "answer_from_context":
            evidence = (args.get("evidence") or {}).get("table")
            if isinstance(evidence, str):
                append_tool_step(
                    steps, h, ctx, created,
                    tool="read_subtable",
                    args={"table": evidence, "limit": 20},
                    think=(
                        f"I read `{evidence}` because it is the current evidence table, and I need to "
                        "see the rows before giving the final answer."
                    ),
                )
            think = action_text(tool, args, clean["question"])
            append_tool_step(steps, h, ctx, created, tool=tool, args=args, think=think)
            ok, pred, gold = score(h, clean["source"]["gold_sql"], args, created)
            if not ok:
                return None, f"final answer mismatch pred={pred} gold={gold}"
            continue

        prefix = ""
        if failed_kept and not used_recovery_prefix:
            prefix = recovery_prefix
            used_recovery_prefix = True
        think = action_text(tool, args, clean["question"], recovery_prefix=prefix)
        status, output, table_name = append_tool_step(
            steps, h, ctx, created, tool=tool, args=args, think=think
        )
        if status != "success":
            return None, f"correct step {tool} failed with status {status}"
        if table_name:
            produced = table_output_name(output)
            if produced:
                old_produced = (
                    (clean_step.get("produces") or {}).get("handle")
                    or (clean_step.get("produces") or {}).get("table")
                    or table_name
                )
                if isinstance(old_produced, str):
                    table_map[old_produced] = produced
        step_map[clean_step["step_id"]] = steps[-1]["step_id"]

    if not steps or steps[-1]["tool_call"]["tool"] != "answer_from_context":
        return None, "no terminal answer"
    out = copy.deepcopy(clean)
    out["trajectory_id"] = f"{clean['trajectory_id']}_recovery_{candidate['failed_sample'].get('sample_index', 0)}"
    out["schema_version"] = "v3-recovery"
    out["label_status"] = "verified"
    out["initial_state"]["dataset_overview"] = overview(Harness(db_path(clean["source"]["db_id"])))
    out["steps"] = steps
    out["final_answer"] = steps[-1]["tool_call"]["arguments"].get("answer")
    out["enrichment"] = {
        "status": "enriched",
        "mode": "failure_recovery",
        "quality_status": "ready",
        "generator": {"model": "deterministic_recovery_builder"},
        "source_candidate": {
            "bucket": candidate.get("bucket"),
            "selection_method": candidate.get("selection_method"),
            "structural_hint": candidate.get("structural_hint"),
            "example_index": candidate.get("example_index"),
            "sample_index": candidate.get("failed_sample", {}).get("sample_index"),
            "sample_failure_type": candidate.get("failed_sample", {}).get("failure_type"),
        },
        "n_failed_prefix_steps": failed_kept,
        "n_steps": len(steps),
    }
    return out, ""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--candidates", nargs="+", required=True)
    parser.add_argument("--clean-trajectories", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--summary", default=None)
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--max-failed-prefix-steps", type=int, default=6)
    parser.add_argument("--allow-dev-analysis", action="store_true")
    args = parser.parse_args()

    candidate_paths = [Path(path) for path in args.candidates]
    if not args.allow_dev_analysis and any(looks_like_dev(path) for path in candidate_paths):
        parser.error("candidate path looks like dev/eval; recovery data must come from train rollouts")

    candidates: list[dict[str, Any]] = []
    for path in candidate_paths:
        candidates.extend(load_jsonl(path))
    if args.limit:
        candidates = candidates[: args.limit]

    clean_by_id = trajectory_index(Path(args.clean_trajectories))
    results: list[dict[str, Any]] = []
    failures: list[dict[str, Any]] = []
    bucket_counts = collections.Counter()
    for candidate in candidates:
        trajectory_id = candidate_trajectory_id(candidate)
        match = TRAIN_ID_RE.match(trajectory_id)
        if not match:
            failures.append({"trajectory_id": trajectory_id, "error": "not a spider_train id"})
            continue
        clean = clean_by_id.get(trajectory_id)
        if clean is None:
            failures.append({"trajectory_id": trajectory_id, "error": "clean trajectory not found"})
            continue
        recovered, err = build_one(candidate, clean, max_failed_prefix_steps=args.max_failed_prefix_steps)
        if recovered is None:
            failures.append({"trajectory_id": trajectory_id, "error": err})
            continue
        results.append(recovered)
        bucket_counts[candidate.get("bucket", "unknown")] += 1

    output = Path(args.output)
    write_jsonl(output, results)
    summary = {
        "inputs": [str(path) for path in candidate_paths],
        "clean_trajectories": args.clean_trajectories,
        "output": str(output),
        "requested_candidates": len(candidates),
        "built": len(results),
        "failed": len(failures),
        "bucket_counts": dict(bucket_counts),
        "failures": failures[:100],
    }
    summary_path = Path(args.summary) if args.summary else output.with_suffix(output.suffix + ".summary.json")
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print(f"-> {output}")
    print(f"-> {summary_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
